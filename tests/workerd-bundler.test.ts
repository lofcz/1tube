/**
 * Tests for the workerd backend bundler.
 *
 * These are not mocked — they invoke esbuild against the real playground
 * fixtures, then either inspect the produced bundle text or import it as
 * an ESM module to exercise the workerd `default.fetch(...)` entrypoint.
 *
 * One esbuild worker is shared across the whole file because esbuild's
 * `stop()` is process-global; we tear it down once in a final cleanup test.
 *
 * The "env shim works at runtime" assertion lives in the workerd e2e test
 * (M1) — the shim defers to any pre-existing `globalThis.Deno` and its
 * per-request env comes from workerd's `env` bindings, so the contract can
 * only be faithfully exercised inside a real workerd process.
 */

import { test } from "bun:test";
import {
  assert,
  assertEquals,
  assertRejects,
  assertStringIncludes,
} from "./_assert.ts";
import { mkdir, mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve as resolvePath } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as esbuild from "esbuild";
import {
  type Bundler,
  createBundler,
  discoverEntrypoints,
  discoverSharedModules,
} from "../src/bundler/core.ts";
import { WORKERD_PROFILE } from "../src/backends/workerd/bundle-profile.ts";

const PROJECT_ROOT = resolvePath(fileURLToPath(new URL("..", import.meta.url)));
const PLAYGROUND = join(PROJECT_ROOT, "playground");
const DENO_JSON = join(PROJECT_ROOT, "deno.json");

// Single bundler per process — esbuild's worker is global. Each test gets
// its own outDir so results don't collide.
let _shared: Bundler | null = null;
function sharedBundler(outDir: string): Bundler {
  if (!_shared) {
    _shared = createBundler({
      profile: WORKERD_PROFILE,
      outDir,
      configPath: DENO_JSON,
    });
    return _shared;
  }
  // Re-create with a different outDir but reuse esbuild's global state by
  // not calling stop on the old one. The factory is cheap (closures only).
  return createBundler({
    profile: WORKERD_PROFILE,
    outDir,
    configPath: DENO_JSON,
  });
}

// Bundling the playground may first `bun install` its npm: deps into the
// managed store, which easily exceeds bun:test's 5s default. A timed-out test
// also gets its child processes (esbuild's service, bun install) killed,
// which would cascade into every later test — so be generous.
const BUNDLE_TIMEOUT_MS = 180_000;

async function makeOutDir(label: string): Promise<string> {
  return await mkdtemp(join(tmpdir(), `1tube-bundler-${label}-`));
}

async function importBundle(bundlePath: string): Promise<{
  fetch: (
    req: Request,
    env?: Record<string, string>,
    ctx?: unknown,
  ) => Promise<Response>;
}> {
  // Cache-bust on every import so a rebuilt bundle isn't shadowed by a
  // stale module from a previous test in the same process.
  const url = pathToFileURL(bundlePath).href + `?v=${crypto.randomUUID()}`;
  // The banner unconditionally installs its own `__edgeFunctionRegistry`.
  // Every bun:test file shares one realm, so a leftover registry would make
  // later suites' standalone handlers (e.g. the Vercel bundle's
  // `_shared/handler.ts`) register into it instead of calling `Deno.serve`.
  // The handler is captured at import time, so restoring right after the
  // import is safe.
  const g = globalThis as Record<string, unknown>;
  const hadRegistry = "__edgeFunctionRegistry" in g;
  const previousRegistry = g.__edgeFunctionRegistry;
  try {
    const mod = await import(url);
    return mod.default;
  } finally {
    if (hadRegistry) g.__edgeFunctionRegistry = previousRegistry;
    else delete g.__edgeFunctionRegistry;
  }
}

test(
  "workerd-bundler: bundles a public function and runs it",
  async () => {
    const outDir = await makeOutDir("hello");
    try {
      const bundler = sharedBundler(outDir);
      const result = await bundler.bundle({
        name: "hello",
        entrypoint: join(PLAYGROUND, "hello", "index.ts"),
      });

      assertEquals(result.name, "hello");
      assert(result.byteLength > 0, "bundle should not be empty");
      assert(result.bundlePath.endsWith("hello.js"));
      assertEquals(result.sourcemapPath, `${result.bundlePath}.map`);

      const text = await readFile(result.bundlePath, "utf8");
      assertStringIncludes(text, "AUTO-GENERATED by 1tube workerd bundler");
      assertStringIncludes(text, "__edgeFunctionRegistry");
      assertStringIncludes(text, "export default");

      const handler = await importBundle(result.bundlePath);
      const res = await handler.fetch(
        new Request("http://localhost/functions/v1/hello"),
        {},
      );
      assertEquals(res.status, 200);
      const body = await res.json();
      assert(typeof body.message === "string");
    } finally {
      await rm(outDir, { recursive: true, force: true });
    }
  },
  BUNDLE_TIMEOUT_MS,
);

test(
  "workerd-bundler: bundles echo and round-trips a JSON body",
  async () => {
    const outDir = await makeOutDir("echo");
    try {
      const bundler = sharedBundler(outDir);
      const result = await bundler.bundle({
        name: "echo",
        entrypoint: join(PLAYGROUND, "echo", "index.ts"),
      });
      const handler = await importBundle(result.bundlePath);

      const req = new Request("http://localhost/functions/v1/echo?x=1", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ hello: "workerd" }),
      });
      const res = await handler.fetch(req, {});
      assertEquals(res.status, 200);
      const body = await res.json() as {
        method: string;
        query: Record<string, string>;
        body: { hello: string };
      };
      assertEquals(body.method, "POST");
      assertEquals(body.query.x, "1");
      assertEquals(body.body.hello, "workerd");
    } finally {
      await rm(outDir, { recursive: true, force: true });
    }
  },
  BUNDLE_TIMEOUT_MS,
);

test(
  "workerd-bundler: authenticated handler sees the auth headers",
  async () => {
    const outDir = await makeOutDir("whoami");
    try {
      const bundler = sharedBundler(outDir);
      const result = await bundler.bundle({
        name: "whoami",
        entrypoint: join(PLAYGROUND, "whoami", "index.ts"),
      });
      const handler = await importBundle(result.bundlePath);

      const req = new Request("http://localhost/functions/v1/whoami", {
        headers: {
          "X-1tube-Auth-User": "user-42",
          "X-1tube-Auth-Email": "user@example.com",
          "X-1tube-Auth-Token": "tok",
          "X-1tube-Auth-Payload": JSON.stringify({ role: "authenticated" }),
        },
      });
      const res = await handler.fetch(req, {});
      assertEquals(res.status, 200);
      const body = await res.json() as {
        userId: string;
        email: string;
        payload: { role: string };
      };
      assertEquals(body.userId, "user-42");
      assertEquals(body.email, "user@example.com");
      assertEquals(body.payload.role, "authenticated");
    } finally {
      await rm(outDir, { recursive: true, force: true });
    }
  },
  BUNDLE_TIMEOUT_MS,
);

test(
  "workerd-bundler: emits the Deno.env shim verbatim into the bundle",
  async () => {
    // Runtime behaviour of the shim is exercised by the e2e workerd test;
    // here we only assert the bundler emits the contract the e2e test
    // relies on.
    const outDir = await makeOutDir("env-shim");
    try {
      const bundler = sharedBundler(outDir);
      const result = await bundler.bundle({
        name: "hello",
        entrypoint: join(PLAYGROUND, "hello", "index.ts"),
      });
      const text = await readFile(result.bundlePath, "utf8");
      assertStringIncludes(text, "__1tubeWorkerEnv");
      assertStringIncludes(text, "__1tubeDenoEnv");
      assertStringIncludes(text, "globalThis.__edgeFunctionRegistry");
      assertStringIncludes(text, 'Object.defineProperty(globalThis, "Deno"');
      // The shim is only installed under real workerd: importing the bundle
      // into this Bun realm must leave the host's globals untouched.
      assertStringIncludes(text, 'typeof Bun !== "undefined"');
      const hadDeno = "Deno" in globalThis;
      await importBundle(result.bundlePath);
      assertEquals("Deno" in globalThis, hadDeno);
    } finally {
      await rm(outDir, { recursive: true, force: true });
    }
  },
  BUNDLE_TIMEOUT_MS,
);

test(
  "workerd-bundler: shared modules are replaced with RPC stubs",
  async () => {
    const root = await mkdtemp(join(tmpdir(), "1tube-shared-fixture-"));
    const outDir = await makeOutDir("shared-stub");
    try {
      await mkdir(join(root, "_shared"), { recursive: true });
      await mkdir(join(root, "needs-profile"), { recursive: true });
      await writeFile(
        join(root, "_shared", "profile-cache.ts"),
        `const cache = new Map([["u1", { claims: ["teacher"] }]]);
export async function getCachedProfile(userId: string) {
  return cache.get(userId) ?? { claims: [] };
}
export function invalidateProfile(userId: string) {
  cache.delete(userId);
}
`,
      );
      await writeFile(
        join(root, "_shared", "handler.ts"),
        `export function serve(handler: (req: Request) => Response | Promise<Response>) {
  (globalThis as any).__edgeFunctionRegistry.register(handler, { public: true });
}
`,
      );
      await writeFile(
        join(root, "needs-profile", "index.ts"),
        `import { serve } from "../_shared/handler.ts";
import { getCachedProfile } from "../_shared/profile-cache.ts";
serve(async () => Response.json(await getCachedProfile("u1")));
`,
      );

      const sharedModules = await discoverSharedModules(root);
      const bundler = createBundler({
        profile: WORKERD_PROFILE,
        outDir,
        sharedModules,
        sourcemap: false,
      });
      const result = await bundler.bundle({
        name: "needs-profile",
        entrypoint: join(root, "needs-profile", "index.ts"),
      });
      const text = await readFile(result.bundlePath, "utf8");
      assertStringIncludes(text, "/modules/");
      assertStringIncludes(text, "/call/");
      assertStringIncludes(text, "getCachedProfile");
      assert(
        !text.includes('new Map([["u1"'),
        "real shared module must not be bundled into isolate",
      );
    } finally {
      await rm(root, { recursive: true, force: true }).catch(() => {});
      await rm(outDir, { recursive: true, force: true }).catch(() => {});
    }
  },
  BUNDLE_TIMEOUT_MS,
);

test(
  "workerd-bundler: produces deterministic output for identical input",
  async () => {
    const outA = await makeOutDir("det-a");
    const outB = await makeOutDir("det-b");
    try {
      const bundlerA = sharedBundler(outA);
      const bundlerB = sharedBundler(outB);
      const a = await bundlerA.bundle({
        name: "hello",
        entrypoint: join(PLAYGROUND, "hello", "index.ts"),
      });
      const b = await bundlerB.bundle({
        name: "hello",
        entrypoint: join(PLAYGROUND, "hello", "index.ts"),
      });
      const textA = await readFile(a.bundlePath, "utf8");
      const textB = await readFile(b.bundlePath, "utf8");
      assertEquals(
        textA,
        textB,
        "identical inputs should yield byte-identical bundles",
      );
    } finally {
      await rm(outA, { recursive: true, force: true });
      await rm(outB, { recursive: true, force: true });
    }
  },
  BUNDLE_TIMEOUT_MS,
);

test(
  "workerd-bundler: bundleAll fans out and returns one result per input",
  async () => {
    const outDir = await makeOutDir("all");
    try {
      const bundler = sharedBundler(outDir);
      const inputs = await discoverEntrypoints(PLAYGROUND);
      assert(
        inputs.length >= 2,
        `expected >=2 playground fns, got ${inputs.length}`,
      );

      const results = await bundler.bundleAll(inputs, { concurrency: 2 });
      assertEquals(results.length, inputs.length);
      for (const r of results) {
        assert(r.byteLength > 0);
        assert((await stat(r.bundlePath)).isFile());
      }
      const names = results.map((r) => r.name);
      assertEquals([...names].sort(), names);
    } finally {
      await rm(outDir, { recursive: true, force: true });
    }
  },
  BUNDLE_TIMEOUT_MS,
);

test(
  "workerd-bundler: reports a useful error for a broken entrypoint",
  async () => {
    const fnDir = await mkdtemp(join(tmpdir(), "1tube-bundler-bad-fn-"));
    try {
      await writeFile(
        join(fnDir, "index.ts"),
        `import { somethingThatDoesNotExist } from "./nope.ts";\n` +
          `console.log(somethingThatDoesNotExist);\n`,
      );

      const outDir = await makeOutDir("bad");
      try {
        const bundler = sharedBundler(outDir);
        // esbuild itself throws an aggregate `Error: Build failed with N error(s)`
        // when bundle() encounters errors with `logLevel: silent`. We don't
        // wrap that — surfacing the original message preserves location info.
        // The assertion just confirms the error mentions the missing module.
        await assertRejects(
          () =>
            bundler.bundle({
              name: "bad",
              entrypoint: join(fnDir, "index.ts"),
            }),
          Error,
          "nope.ts",
        );
      } finally {
        await rm(outDir, { recursive: true, force: true });
      }
    } finally {
      await rm(fnDir, { recursive: true, force: true });
    }
  },
  BUNDLE_TIMEOUT_MS,
);

test(
  "workerd-bundler: discoverEntrypoints skips _shared and underscored dirs",
  async () => {
    const inputs = await discoverEntrypoints(PLAYGROUND);
    for (const i of inputs) {
      assert(!i.name.startsWith("_"), `should skip underscored dir: ${i.name}`);
      assert(
        !i.name.endsWith("_shared"),
        `should skip *_shared dir: ${i.name}`,
      );
    }
    for (const i of inputs) {
      assert((await stat(i.entrypoint)).isFile());
    }
  },
  BUNDLE_TIMEOUT_MS,
);

